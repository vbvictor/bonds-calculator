/**
 * Подтверждённые даты заседаний Совета директоров Банка России по ключевой ставке.
 *
 * Источник: https://cbr.ru/dkp/cal_mp/
 * Последняя сверка: 21.09.2026
 *
 * Заседания проходят 8 раз в год, по пятницам. Решение публикуется в 13:30 МСК.
 * Календарь публикуется примерно на год вперёд — на момент сверки даты на 2027 год
 * ещё не опубликованы. Всё, что за пределами этого списка, пользователь задаёт сам,
 * и такие точки помечаются confidence: 'estimated'.
 *
 * ВАЖНО: с 2027 года изменённая ключевая ставка начинает действовать не с понедельника
 * после заседания, а с ближайшей среды. На помесячной модели это не сказывается,
 * но при переходе на подневный шаг учесть придётся.
 */

export const CBR_MEETINGS_CONFIRMED: readonly string[] = [
  // 2026 — прошедшие, оставлены для полноты и для расчётов с ретроспективной датой старта
  '2026-02-13',
  '2026-03-20',
  '2026-04-24',
  '2026-06-19',
  '2026-07-24',
  '2026-09-11',
  // 2026 — предстоящие
  '2026-10-23',
  '2026-12-18',
] as const;

/**
 * Типичные интервалы между заседаниями в месяцах, в порядке годового цикла.
 * Используется генератором сетки для режима «как у ЦБ, 8 раз в год».
 * Выведено из фактического календаря 2024–2026 годов.
 */
export const CBR_CADENCE_MONTHS: readonly number[] = [2, 1, 1, 2, 1, 2, 1, 2] as const;

/** Дата последней сверки календаря с сайтом ЦБ. Показывать в UI рядом с пометками. */
export const CALENDAR_CHECKED_AT = '2026-09-21';

/**
 * Является ли дата подтверждённым заседанием.
 * Сравнение по строке ISO в формате YYYY-MM-DD.
 */
export function isConfirmedMeeting(isoDate: string): boolean {
  return CBR_MEETINGS_CONFIRMED.includes(isoDate);
}

/**
 * Ближайшие подтверждённые заседания начиная с указанной даты включительно.
 * Возвращает пустой массив, если календарь исчерпан — это нормальный случай,
 * дальше работает генератор сетки.
 */
export function upcomingMeetings(fromIso: string, limit = 8): string[] {
  return CBR_MEETINGS_CONFIRMED.filter((d) => d >= fromIso).slice(0, limit);
}
